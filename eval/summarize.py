"""Aggregate results/<arm>.jsonl files into results/summary.md and results/summary.json.

Statistics:
* EX with a Wilson 95% score interval.
* McNemar's exact test (two-sided binomial on discordant pairs) between arms, which is the
  right paired test because every arm answers the same 200 questions.
* Retry fix rate = (first attempt wrong and final answer right) / (first attempt wrong).
"""

from __future__ import annotations

import json
import math

import numpy as np
from scipy.stats import binomtest

from t2s.config import RESULTS_DIR

ARM_ORDER = ["A0", "A1", "A2", "A3", "A1R", "A0-3b", "A3-3b"]
LEVELS = ["easy", "medium", "hard", "extra"]
PAIRS = [
    ("A0", "A1"), ("A1", "A2"), ("A2", "A3"), ("A0", "A2"), ("A0", "A3"),
    ("A1", "A1R"), ("A0", "A1R"), ("A0", "A0-3b"), ("A3", "A3-3b"), ("A0", "A3-3b"),
]


def wilson(k: int, n: int, z: float = 1.959964) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    den = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / den
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return (max(0.0, centre - half), min(1.0, centre + half))


def mcnemar(a: list[bool], b: list[bool]) -> dict:
    """b01 = a wrong & b right, b10 = a right & b wrong; exact two-sided p-value."""
    b01 = sum((not x) and y for x, y in zip(a, b))
    b10 = sum(x and (not y) for x, y in zip(a, b))
    n = b01 + b10
    p = 1.0 if n == 0 else binomtest(min(b01, b10), n, 0.5).pvalue
    return {"b01_fixed": b01, "b10_broken": b10, "p_value": p}


def load(arm: str) -> list[dict]:
    path = RESULTS_DIR / f"{arm}.jsonl"
    if not path.exists():
        return []
    rows = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]
    return sorted(rows, key=lambda r: r["id"])


def arm_stats(rows: list[dict]) -> dict:
    n = len(rows)
    k = sum(r["correct"] for r in rows)
    lat = np.array([r["latency_ms"] for r in rows])
    s = {
        "n": n,
        "ex": k / n,
        "ex_ci95": wilson(k, n),
        "per_hardness": {},
        "mean_attempts": float(np.mean([r["attempts"] for r in rows])),
        "mean_tokens_in": float(np.mean([r["tokens_in"] for r in rows])),
        "mean_tokens_out": float(np.mean([r["tokens_out"] for r in rows])),
        "latency_p50_ms": float(np.percentile(lat, 50)),
        "latency_p95_ms": float(np.percentile(lat, 95)),
        "exec_errors": sum(r["status"] in ("error", "guard") for r in rows),
        "guard_rejections_final": sum(r["status"] == "guard" for r in rows),
    }
    for lv in LEVELS:
        sub = [r for r in rows if r["hardness"] == lv]
        kk = sum(r["correct"] for r in sub)
        s["per_hardness"][lv] = {"n": len(sub), "ex": kk / len(sub) if sub else 0.0, "ci95": wilson(kk, len(sub))}
    first_fail = [r for r in rows if not r["first_correct"]]
    if any(r["attempts"] > 1 for r in rows):
        fixed = sum(r["correct"] for r in first_fail)
        broken = sum(r["first_correct"] and not r["correct"] for r in rows)
        s["retry"] = {
            "first_attempt_ex": sum(r["first_correct"] for r in rows) / n,
            "first_attempt_failures": len(first_fail),
            "fixed": fixed,
            "fix_rate": fixed / len(first_fail) if first_fail else 0.0,
            "broken_by_retry": broken,
            "questions_with_retry": sum(r["attempts"] > 1 for r in rows),
            "retry_triggers": {
                kind: sum(1 for r in rows if r["error_trace"] and r["error_trace"][0]["kind"] == kind)
                for kind in ("error", "guard", "empty")
            },
        }
    rec = [r["link_recall"] for r in rows if r.get("link_recall") is not None]
    if rec:
        s["linking"] = {
            "mean_table_recall": float(np.mean(rec)),
            "full_recall_share": float(np.mean([x == 1.0 for x in rec])),
            "pruned_share": float(np.mean([len(r["linked_tables"]) < r["n_tables"] for r in rows])),
            "mean_tables_kept": float(np.mean([len(r["linked_tables"]) for r in rows])),
            "mean_tables_total": float(np.mean([r["n_tables"] for r in rows])),
        }
    return s


def pct(x: float) -> str:
    return f"{100 * x:.1f}"


def main() -> dict:
    data = {arm: load(arm) for arm in ARM_ORDER}
    data = {a: r for a, r in data.items() if r}
    stats = {a: arm_stats(r) for a, r in data.items()}
    tests = {}
    for a, b in PAIRS:
        if a in data and b in data and [r["id"] for r in data[a]] == [r["id"] for r in data[b]]:
            tests[f"{a}->{b}"] = mcnemar([r["correct"] for r in data[a]], [r["correct"] for r in data[b]])

    md = ["# Ablation summary", "", "Generated by `python -m eval.summarize` from `results/<arm>.jsonl`.", ""]
    md += ["| Arm | n | EX % | Wilson 95% CI | easy | medium | hard | extra | mean attempts "
           "| tokens in / out | p50 / p95 latency (s) |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    for a, s in stats.items():
        ph = s["per_hardness"]
        md.append(
            f"| {a} | {s['n']} | {pct(s['ex'])} | {pct(s['ex_ci95'][0])}-{pct(s['ex_ci95'][1])} | "
            + " | ".join(f"{pct(ph[lv]['ex'])} (n={ph[lv]['n']})" for lv in LEVELS)
            + f" | {s['mean_attempts']:.2f} | {s['mean_tokens_in']:.0f} / {s['mean_tokens_out']:.0f} | "
            f"{s['latency_p50_ms'] / 1000:.2f} / {s['latency_p95_ms'] / 1000:.2f} |"
        )
    if tests:
        md += ["", "## McNemar exact test (paired, same question ids)", "",
               "| Comparison | fixed (wrong->right) | broken (right->wrong) | p-value |", "|---|---|---|---|"]
        for k, t in tests.items():
            md.append(f"| {k} | {t['b01_fixed']} | {t['b10_broken']} | {t['p_value']:.4f} |")
    for a, s in stats.items():
        if "retry" in s:
            r = s["retry"]
            md += ["", f"## Self-correction ({a})", "",
                   f"- First-attempt EX: {pct(r['first_attempt_ex'])}% -> final EX: {pct(s['ex'])}%",
                   f"- First-attempt failures: {r['first_attempt_failures']}; fixed by retries: {r['fixed']} "
                   f"(fix rate {pct(r['fix_rate'])}%); correct answers broken by a retry: {r['broken_by_retry']}",
                   f"- Questions that triggered a retry: {r['questions_with_retry']} "
                   f"(first trigger: {r['retry_triggers']})"]
    for a, s in stats.items():
        if "linking" in s:
            li = s["linking"]
            md += ["", f"## Schema linking ({a})", "",
                   f"- Mean gold-table recall: {li['mean_table_recall']:.3f}; "
                   f"questions with full recall: {pct(li['full_recall_share'])}%",
                   f"- Questions where linking pruned at least one table: {pct(li['pruned_share'])}% "
                   f"(mean tables kept {li['mean_tables_kept']:.2f} of {li['mean_tables_total']:.2f})"]
            break
    (RESULTS_DIR / "summary.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    (RESULTS_DIR / "summary.json").write_text(json.dumps({"arms": stats, "mcnemar": tests}, indent=1), encoding="utf-8")
    print("\n".join(md))
    return stats


if __name__ == "__main__":
    main()
